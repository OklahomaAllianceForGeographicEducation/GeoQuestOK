// scripts/import-trail-images.mjs
// Reads supabase/trail-images.json (a git-tracked, version-controlled record
// of each trail's cover image + license/attribution info) and emits SQL that
// updates ONLY the `image_url` column, one trail at a time. It never touches
// any other column, so it's safe to re-run at any point without risk of
// wiping route/landmark/name data — and because the source manifest lives in
// the repo, the URLs and their licensing info survive even if the database
// gets reset (unlike a value only ever pasted directly into Supabase).
//
// Usage: node scripts/import-trail-images.mjs [manifestPath] [outputPath]

import fs from 'fs';
import path from 'path';
import process from 'process';

const manifestPath = process.argv[2] ?? path.resolve(process.cwd(), 'supabase', 'trail-images.json');
const outputPath = process.argv[3] ?? path.resolve(process.cwd(), 'supabase', 'trail-images.upsert.sql');

function sqlString(value) {
    return `'${String(value).replace(/'/g, "''")}'`;
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (!Array.isArray(manifest)) {
    throw new Error('Expected trail-images.json to contain an array of { trail_id, image_url, ... } entries.');
}

const ready = manifest.filter((entry) => entry.image_url && entry.image_url.trim());
const pending = manifest.filter((entry) => !entry.image_url || !entry.image_url.trim());

if (ready.length === 0) {
    console.log('No entries in trail-images.json have an image_url yet — nothing to write.');
    process.exit(0);
}

const lines = [];
lines.push('-- Generated by scripts/import-trail-images.mjs. Paste into the Supabase SQL editor.');
lines.push('-- Only touches trails.image_url — no other column is affected.');
lines.push('begin;');
lines.push('');

for (const entry of ready) {
    lines.push(
        `update public.trails set image_url = ${sqlString(entry.image_url.trim())} where id = ${sqlString(entry.trail_id)};` +
        (entry.attribution ? ` -- ${entry.attribution}` : '')
    );
}

lines.push('');
lines.push('commit;');

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, lines.join('\n') + '\n');

console.log(`Wrote ${ready.length} image_url update(s) to ${outputPath}`);
if (pending.length > 0) {
    console.log(`Still missing an image_url in the manifest: ${pending.map((e) => `${e.trail_id} (${e.name})`).join(', ')}`);
}

// scripts/merge-route66-legs.mjs
// One-time merge: Route 66 Eastbound no longer exists as its own trail row
// (its id got reused for an unrelated trail), and Route66's route_geojson
// has already been extended to cover the full Texola-to-tri-state-corner
// path -- but its landmarks_geojson/quiz_questions still only cover the
// westbound leg. This combines both legs' landmark GeoJSON files into one
// landmarks_geojson + one quiz_questions upsert for a single trail id.
//
// The westbound leg's ids/mile markers are kept as-is (it already owns ids
// 1-20 in quiz_questions from the original import). The eastbound leg's
// feature ids get +20 (avoids collisions) and its NearestMile values get
// +125 (westbound's final "Journey's End: Reaching Oklahoma City" mile), so
// the combined landmark list reads as one continuous 0-353 mile journey
// instead of two separate 0-125 / 0-228 ones.
//
// Usage: node scripts/merge-route66-legs.mjs <trailId> <westboundPath> <eastboundPath> <outputPath>

import fs from 'fs';
import path from 'path';
import process from 'process';

const GRADE_BANDS = ['elementary', 'middle', 'high'];
const ID_OFFSET = 20;
const MILE_OFFSET = 125;

const [, , trailId, westPath, eastPath, outPath] = process.argv;
if (!trailId || !westPath || !eastPath || !outPath) {
    console.error('Usage: node scripts/merge-route66-legs.mjs <trailId> <westboundPath> <eastboundPath> <outputPath>');
    process.exit(1);
}

function readJson(filePath) {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function sqlString(value) {
    return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJsonb(value) {
    return `${sqlString(JSON.stringify(value))}::jsonb`;
}

function sqlTextArray(values) {
    if (!Array.isArray(values) || values.length === 0) return 'ARRAY[]::text[]';
    return `ARRAY[${values.map(sqlString).join(', ')}]::text[]`;
}

function sqlNullable(value) {
    return value === null || value === undefined || value === '' ? 'null' : sqlString(value);
}

function toInformationalFeature(feature, idOffset, mileOffset) {
    const rawMile = feature.properties?.NearestMile ?? 0;
    return {
        type: 'Feature',
        id: feature.id + idOffset,
        geometry: feature.geometry,
        properties: {
            title: feature.properties?.title ?? 'Landmark',
            description: feature.properties?.description ?? null,
            funFact: feature.properties?.funFact ?? null,
            NearestMile: Math.round((rawMile + mileOffset) * 100) / 100,
            category: feature.properties?.category ?? null,
        },
    };
}

function buildQuizRows(trailId, feature, idOffset) {
    const rows = [];
    const landmarkId = String(feature.id + idOffset);
    const landmarkTitle = feature.properties?.title ?? 'Landmark';
    const quizzes = feature.properties?.quizzes ?? {};

    for (const band of GRADE_BANDS) {
        const quiz = quizzes[band];
        if (!quiz) continue;

        const wrongAnswers = Array.isArray(quiz.wrongAnswers) ? quiz.wrongAnswers.filter(Boolean) : [];
        if (!quiz.question || !quiz.answer || wrongAnswers.length === 0) {
            console.warn(`Skipping ${landmarkTitle} (feature ${landmarkId}, ${band}): missing question/answer/wrongAnswers.`);
            continue;
        }

        rows.push({
            trail_id: trailId,
            landmark_id: landmarkId,
            landmark_title: landmarkTitle,
            grade_band: band,
            subject: quiz.type ?? 'general',
            standard_code: quiz.standard ?? null,
            question: quiz.question,
            correct_answer: quiz.answer,
            wrong_answers: wrongAnswers,
        });
    }

    return rows;
}

const west = readJson(westPath);
const east = readJson(eastPath);

const westInfo = west.features.map((f) => toInformationalFeature(f, 0, 0));
const eastInfo = east.features.map((f) => toInformationalFeature(f, ID_OFFSET, MILE_OFFSET));
const landmarksGeojson = { type: 'FeatureCollection', features: [...westInfo, ...eastInfo] };

const quizRows = [
    ...west.features.flatMap((f) => buildQuizRows(trailId, f, 0)),
    ...east.features.flatMap((f) => buildQuizRows(trailId, f, ID_OFFSET)),
];

const lines = [];
lines.push('-- Generated by scripts/merge-route66-legs.mjs. Paste into the Supabase SQL editor.');
lines.push('-- Merges the westbound (Classic Journey) and eastbound Route 66 legs into a single');
lines.push(`-- trail's landmarks_geojson + quiz_questions (trail id ${trailId}). Does NOT touch`);
lines.push('-- route_geojson (already covers the full path) or the trails.miles column (already');
lines.push('-- the correct computed distance for that full path -- note this is a larger number');
lines.push('-- than the sum of the two legs\' narrative mile markers below, since those were');
lines.push('-- hand-authored approximations, not GPS-path distance; landmarks still "unlock"');
lines.push('-- correctly in order, there\'s just a gap with no new landmarks near the very end.');
lines.push('begin;');
lines.push('');
lines.push(`update public.trails set landmarks_geojson = ${sqlJsonb(landmarksGeojson)} where id = ${sqlString(trailId)};`);
lines.push('');

if (quizRows.length > 0) {
    const columns = [
        'trail_id', 'landmark_id', 'landmark_title', 'grade_band', 'subject',
        'standard_code', 'question', 'correct_answer', 'wrong_answers',
    ];
    const valueLines = quizRows.map((row) => {
        const values = [
            sqlString(row.trail_id), sqlString(row.landmark_id), sqlString(row.landmark_title),
            sqlString(row.grade_band), sqlString(row.subject), sqlNullable(row.standard_code),
            sqlString(row.question), sqlString(row.correct_answer), sqlTextArray(row.wrong_answers),
        ].join(', ');
        return `(${values})`;
    });
    const updateColumns = columns
        .filter((c) => !['trail_id', 'landmark_id', 'grade_band'].includes(c))
        .map((c) => `${c} = excluded.${c}`)
        .join(', ');
    lines.push(
        `insert into public.quiz_questions (${columns.join(', ')}) values\n${valueLines.join(',\n')}\n` +
        `on conflict (trail_id, landmark_id, grade_band) do update set ${updateColumns};`
    );
    lines.push('');
}

lines.push('commit;');

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n') + '\n');

console.log(
    `Wrote ${landmarksGeojson.features.length} landmark(s) (${westInfo.length} westbound + ${eastInfo.length} eastbound) ` +
    `and ${quizRows.length} quiz question row(s) for trail "${trailId}" to ${outPath}`
);
